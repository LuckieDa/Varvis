import fs from 'node:fs';
const source = fs.readFileSync(new URL('../../varvis-client-pro/src/pages/varvis/ChromosomeVisualization/utils/acmgInput.js', import.meta.url), 'utf8');
const { prepareSimplifiedInputs, buildSimplifiedCaseDeclaration } = await import(
    `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`,
);
