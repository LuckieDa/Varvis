const declaration = buildSimplifiedCaseDeclaration(options, options.analysisId, prepareSimplifiedInputs(options), undefined, 'SYNTHETIC');
fs.writeFileSync(process.argv[3], `${JSON.stringify(declaration, null, 2)}\n`, { flag: 'wx' });
