"""Independent finite-condition regressions; all case statements are synthetic.

The SVI weights are not generated by the implementation. Source-method proof
and the existence of contradictory claims are deliberately separate questions.
"""
from copy import deepcopy
import unittest

from pm3_observations import phase_observations
from pm3_specification_context import (
    SpecificationContext, PHASE_DELEGATION, APPROVED_PARTNER, POLICY, SOURCE_SHA256, program)
from test_pm3_specification_context import specification


def phase_case(*statements, initial='UNKNOWN'):
    facts = []
    for i, value in enumerate(statements):
        facts.append({'field': 'reportedPhase', 'sourceValue': value, 'subject': 'PROBAND', 'issues': [],
            'ownership': {'method': 'EXPLICIT_UNIQUE_CASE_ROW', 'container': 'row-1',
                          'cellText': value, 'columnHeading': 'Phase', 'headingUnitId': 'header'},
            'citation': {'unitId': 'cell-'+str(i), 'quote': value}})
    return {'facts': facts, 'semantics': {'observations': [
        {'phase': initial, 'phaseBasis': 'PARENTAL_RESULTS' if initial == 'TRANS' else 'NOT_REPORTED',
         'facts': [{'container': 'row-1', 'field': 'targetVariant', 'value': 'c.1A>G'}]}]}}


class FiniteConditions(unittest.TestCase):
    def test_specification_sentence_after_final_list_is_not_a_new_token_or_a_hidden_dependency(self):
        from pm3_partner_qualification import qualify
        from pm3_partner_sources import applied_criteria_statements
        from test_pm3_partner_source_policy import SourcePolicy
        source = SourcePolicy().source(); row = source['assertions'][0]
        path = '/ClinicalAssertion[1]/Classification[1]/Comment[1]'
        text = 'ACMG/AMP criteria applied: PS3, PM2, PP3. Classification performed using https://doi.org/10.5281/zenodo.9999999.'
        row['comments'] = [{'text': text, 'xpath': path, 'scope': 'CLASSIFICATION'}]
        row['criteriaStatements'] = applied_criteria_statements(row['comments'], 'VCV000000123')
        self.assertEqual('UNPARSED_SOURCE_STATEMENT', row['criteriaStatements'][0]['status'])
        result = qualify(source, SourcePolicy.context)
        self.assertEqual('VERIFIED', result['independentClassification'])
        self.assertEqual(text, result['sourceAssertions'][0]['criteriaStatements'][0]['originalText'])
        self.assertEqual('UNPARSED_SOURCE_STATEMENT', row['criteriaStatements'][0]['status'])
        for suffix in [' PM3 also applied.', ' ACMG/AMP criteria applied: PS2, PM2.', ' PS3 was not applicable.']:
            changed = deepcopy(source); comment = changed['assertions'][0]['comments'][0]; comment['text'] += suffix
            changed['assertions'][0]['criteriaStatements'] = applied_criteria_statements([comment], 'VCV000000123')
            self.assertEqual('UNKNOWN', qualify(changed, SourcePolicy.context)['independentClassification'])

    def check_list_tail(self, suffix, expected):
        from pm3_partner_qualification import qualify
        from pm3_partner_sources import applied_criteria_statements
        from pm3_partner_graph import PartnerDependencyGraph
        from test_pm3_partner_source_policy import SourcePolicy
        source = SourcePolicy().source(); row = source['assertions'][0]
        text = 'ACMG/AMP criteria applied: PS3, PM2, PP3. '+suffix
        row['comments'] = [{'text': text, 'xpath': '/ClinicalAssertion[1]/Classification[1]/Comment[1]', 'scope': 'CLASSIFICATION'}]
        row['criteriaStatements'] = applied_criteria_statements(row['comments'], 'VCV000000123')
        self.assertEqual('UNPARSED_SOURCE_STATEMENT', row['criteriaStatements'][0]['status'])
        before = deepcopy(source)
        target = {'allele': {'assembly': 'GRCh38', 'contig': '1', 'position': 1, 'reference': 'C', 'alternate': 'T'}}
        partner = {'allele': {**target['allele'], 'position': 2}}
        graph = PartnerDependencyGraph(None, None, None, target, 'TEST', SourcePolicy.context)
        for result in (qualify(source, SourcePolicy.context), graph.assess(source, partner)):
            with self.subTest(suffix=suffix, graph='dependencyGraph' in result):
                self.assertEqual(expected, result['independentClassification'])
                self.assertEqual('Pathogenic', result['sourceAssertions'][0]['sourceClassification'])
                self.assertEqual(text, result['sourceAssertions'][0]['criteriaStatements'][0]['originalText'])
                if expected == 'VERIFIED':
                    self.assertEqual('PATHOGENIC', result['classification']); self.assertEqual([], result['issues'])
                else:
                    self.assertEqual('UNKNOWN', result['classification']); self.assertNotIn('qualifiedScvs', result)
                    use = result['sourceAssertions'][0]['criteriaListUse']
                    self.assertEqual(expected, use['status']); self.assertEqual(suffix, use['statement'])
                    self.assertEqual(row['comments'][0]['xpath'], use['sourceLocator'])
                    self.assertTrue(result['issues'])
        self.assertEqual(before, source)

    def test_exact_source_denial_of_the_final_list_never_qualifies_in_direct_or_graph_entry(self):
        for suffix in ['This list was not used for the final classification.',
                       'None of these criteria was used for the final classification.']:
            self.check_list_tail(suffix, 'CONFLICT')

    def test_uncertain_or_planned_list_use_stays_unestablished_in_direct_and_graph_entry(self):
        for suffix in ['These criteria may be used for the final classification.',
                       'It is unclear whether this list was used for the final classification.']:
            self.check_list_tail(suffix, 'UNKNOWN')

    def test_method_prose_and_unrelated_population_negation_preserve_complete_list_qualification(self):
        for suffix in ['Classification performed using https://doi.org/10.5281/zenodo.9999999.',
                       'This variant was not observed in population databases.',
                       'Classification performed using https://doi.org/10.5281/zenodo.9999999. This variant was not observed in population databases.']:
            self.check_list_tail(suffix, 'VERIFIED')

    def test_normal_native_table_populates_the_real_contract_slots_before_phase_qualification(self):
        from test_pm3_automatic_facts import source
        from pm3_observations import native_projection
        from xml.sax.saxutils import escape
        for declared, molecular, expected in [
                ('trans', 'trans', 'TRANS'), ('cis', 'cis', 'CIS'),
                ('trans', 'cis', 'CONFLICT'), ('cis', 'trans', 'CONFLICT')]:
            values = [('Case', '1'), ('Gene', 'EXAMPLE'), ('Allele 1', 'c.2C>G'), ('Allele 2', 'c.3C>T'),
                      ('Transcript', 'NM_000001.1'), ('Phase', declared),
                      ('Phase method', 'Cloning and sequencing of both alleles confirmed the variants in '+molecular+'.')]
            body = '<table-wrap id="t"><table><thead><tr>'+''.join('<th>'+h+'</th>' for h,v in values)+\
                '</tr></thead><tbody><tr>'+''.join('<td>'+escape(v)+'</td>' for h,v in values)+\
                '</tr></tbody></table></table-wrap>'
            case = native_projection(source(body), {'geneSymbol': 'EXAMPLE', 'variantAliases': ['c.2C>G']}, 1)['cases'][0]
            self.assertEqual(expected, case['semantics']['observations'][0]['phase'])
            self.assertEqual({'reportedPhase', 'phaseMethod'},
                {f['field'] for f in case['facts'] if f['producer'] == 'SOURCE_NATIVE_LITERAL_TABLE_PHASE'})
            self.assertTrue(all(f['citation']['quote'] for f in case['facts']))

    def test_molecular_and_bare_opposite_claims_conflict_in_both_directions_and_orders(self):
        for molecular, bare in [
                ('Cloning and sequencing of both alleles confirmed the variants in cis.', 'trans'),
                ('Cloning and sequencing of both alleles confirmed the variants in trans.', 'cis')]:
            for statements in ((molecular, bare), (bare, molecular)):
                with self.subTest(statements=statements):
                    case = phase_case(*statements); phase_observations(case)
                    self.assertEqual('CONFLICT', case['semantics']['observations'][0]['phase'])
                    self.assertEqual(3, len(case['semantics']['observations'][0]['facts']))

    def test_bare_trans_is_not_a_confirmed_method_but_explicit_cis_is_not_unknown(self):
        for statements, expected in [(['trans'], 'UNKNOWN'), (['cis'], 'CIS'),
                (['Cloning and sequencing of both alleles confirmed the variants in trans.'], 'TRANS'),
                (['Cloning and sequencing of both alleles confirmed the variants in cis.'], 'CIS'),
                (['cis', 'trans'], 'CONFLICT'), (['cis', 'unknown'], 'CONFLICT')]:
            with self.subTest(statements=statements):
                case = phase_case(*statements); phase_observations(case)
                self.assertEqual(expected, case['semantics']['observations'][0]['phase'])

    def test_linked_supplement_reads_unknown_only_from_the_anchored_row(self):
        from pm3_supplement_diplotype import attach
        from test_pm3_automatic_facts import source
        pair = 'EXAMPLE; Chr1:[101A>G](;)[102C>T]; NM_000001.1:c.[1A>G](;)[2C>T]; NP_000001.1:p.[(Thr1Ala)](;)[(Thr1Ile)]'
        headings = ['Case#', 'Samples', 'Variant', 'Result', 'Zygosity', 'Phenotype classification']
        unphased = '1 pathogenic and 1 likely pathogenic variant (phase unknown)'
        for result, expected in [(unphased, 'EXPLICIT_SOURCE_PHASE_UNKNOWN'), ('', 'NOT_REPORTED'),
                                 ('phase was not unknown', None)]:
            with self.subTest(result=result):
                s = source('<p>In this study, 2 consecutive unrelated probands with retinal dystrophy '
                           'tested in our laboratory from 2020 to 2021, were included.</p>')
                s['main']['links'].append({'kind': 'media', 'href': 'appendix.docx'})
                rows = [headings, ['1', 'proband', pair, result, 'two heterozygous variants', 'Retinal dystrophy'],
                        ['2', 'proband', pair, unphased, 'two heterozygous variants', 'Retinal dystrophy']]
                for r, values in enumerate(rows, 1):
                    for c, value in enumerate(values, 1):
                        cell = f'R{r}C{c}'
                        s['units'].append({'unitId': cell, 'kind': 'SUPPLEMENT_CELL', 'cell': cell, 'text': value,
                                           'sourcePart': 'word/document.xml', 'sheet': 'table', 'sourceSha256': 'b'*64,
                                           'originalName': 'appendix.docx'})
                case = {'caseLabel': '1', 'anchors': [{'unitId': 'R2C1'}], 'semantics': {'observations': []},
                        'originAssertions': [{'proposal': 'AUTHOR_COHORT'}], 'primarySourceQualification': {}, 'paperPmid': '123'}
                attach(s, case, {'geneSymbol': 'EXAMPLE', 'variantAliases': ['c.1A>G']})
                self.assertEqual(expected is not None, bool(case['semantics']['observations']))
                if expected:
                    observation, = case['semantics']['observations']
                    self.assertEqual(expected, observation['phaseBasis'])
                    self.assertEqual(['R2C4'] if result else [], [
                        f['citation']['unitId'] for f in observation['facts'] if f['field'] == 'phaseText'])

    def test_parental_proof_cannot_hide_an_opposing_claim_and_other_case_is_not_borrowed(self):
        case = phase_case('cis', initial='TRANS'); phase_observations(case)
        self.assertEqual('CONFLICT', case['semantics']['observations'][0]['phase'])
        case = phase_case('Cloning and sequencing of both alleles confirmed the variants in trans.')
        case['facts'][0]['ownership']['container'] = 'row-other'
        phase_observations(case)
        self.assertEqual('UNKNOWN', case['semantics']['observations'][0]['phase'])

    def test_released_finite_forms_do_not_inherit_unread_extra_conditions(self):
        s = specification()['original']; c = s['ld']['CriteriaCode'][0]['entContent']
        for d in c['strengthDescriptor']:
            d['text'] = PHASE_DELEGATION
        self.assertEqual('SVI_PHASE_METHOD', program(s, c)['family'])
        c['instructionsToUse'] = APPROVED_PARTNER
        self.assertEqual('SVI_PHASE_AND_APPROVED_PARTNER', program(s, c)['family'])
        for field, value in [('additionalComments', 'Requires another clinical prerequisite'),
                             ('unknownCondition', 'required')]:
            changed = deepcopy(c); changed[field] = value
            self.assertIsNone(program(s, changed))

    def test_explicit_general_svi_retains_source_and_local_only_absence(self):
        supply = SpecificationContext.__new__(SpecificationContext)
        supply.specifications = []
        supply.source = {'scope': 'PINNED_RELEASED_LOCAL_SNAPSHOT', 'catalogRawSha256': 'a'*64,
                         'worldwideAbsenceClaim': False, 'priorBa1ApprovalInherited': False}
        row = {'identities': {'target': {'status': 'LOCAL_IDENTITY_VERIFIED', 'hgncId': 'HGNC:1', 'geneSymbol': 'TEST'}},
               'diseaseContext': {'qualification': 'VERIFIED', 'inheritance': 'AR', 'diseaseId': 'MONDO:0000001'}}
        selected = supply.select(row)
        self.assertEqual('SELECTED', selected['status']); self.assertEqual(POLICY, selected['policy'])
        self.assertEqual(SOURCE_SHA256, selected['generalPolicy']['sourceRawSha256'])
        self.assertFalse(selected['source']['worldwideAbsenceClaim'])
        row['diseaseContext']['qualification'] = 'UNKNOWN'
        self.assertEqual('UNRESOLVED', supply.select(row)['status'])


