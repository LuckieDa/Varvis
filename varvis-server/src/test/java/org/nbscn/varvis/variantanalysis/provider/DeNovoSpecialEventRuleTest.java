    @Test void verifiedPartnerMayKeepUnknownPhaseAndMixedPositivePartnerStatesRemainExplicitlyUnimplemented() throws Exception {
        JsonNode fixture = pythonPartnerFixture();
        JsonNode core = fixture.path("core"), values = core.path("values"), target = values.path("/context/allele");
        var group = new Group("GRCh38:1:100:A:G", values.path("/context/hgncId").asText(),
                values.path("/context/diseaseId").asText(), values.path("/context/inheritance").asText());
        var policy = svi();
        JsonNode partnerAllele = core.at("/specialEvent/partner/allele");
        var partnerRead = DeNovoPartnerEvidence.read(core, target, partnerAllele, group);
        assertTrue(partnerRead.issues().isEmpty(), partnerRead.toString());
        var partner = partnerRead.value(); assertNotNull(partner);
        var hasPartner = ((ObjectNode) core.path("specialEvent")).deepCopy();
        ((ObjectNode) hasPartner.path("partner")).put("phase", "UNKNOWN");
        var specialRead = DeNovoSpecialEvent.read(hasPartner, SOURCE_SHA, target, group, policy.specialEvents(), null, partner);
        assertTrue(specialRead.issues().isEmpty(), specialRead.toString());
        var special = specialRead.value(); assertNotNull(special);
        assertEquals("UNKNOWN", special.snapshot().at("/partner/phase").asText());
        var qualified = observation("verified-partner", group, Phenotype.CONSISTENT_HIGH_HETEROGENEITY,
                FamilyHistory.COMPATIBLE, special, SOURCE_SHA);
        var alone = calculator.evaluate(group, policy, List.of(qualified));
        assertEquals("MET", alone.status(), alone.toString()); assertEquals("SUPPORTING", alone.strength());
        assertEquals(2, alone.rawQuarterPoints()); assertEquals(2, alone.effectiveQuarterPoints());
        assertEquals("NONE", alone.strengthAdjustment());
        var requiredPartner = calculator.evaluate(group, policy(DeNovoEventPolicy.Mode.SVI_1_1_SECOND_ALLELE_REQUIRED), List.of(qualified));
        assertEquals("MET", requiredPartner.status()); assertEquals("SUPPORTING", requiredPartner.strength());
        var cisEvent = hasPartner.deepCopy(); ((ObjectNode) cisEvent.path("partner")).put("phase", "CIS");
        var cisRead = DeNovoSpecialEvent.read(cisEvent, SOURCE_SHA, target, group, policy.specialEvents(), null, partner);
        assertTrue(cisRead.issues().isEmpty()); var cisFacts = cisRead.value(); assertNotNull(cisFacts);
        assertEquals("CIS", cisFacts.snapshot().at("/partner/phase").asText());
        var cisResult = calculator.evaluate(group, policy, List.of(observation("cis-partner", group,
                Phenotype.CONSISTENT_HIGH_HETEROGENEITY, FamilyHistory.COMPATIBLE, cisFacts, SOURCE_SHA)));
        assertEquals("SUPPORTING", cisResult.strength()); assertEquals(2, cisResult.effectiveQuarterPoints());
        // This is new-event support only: no trans assertion or PM3 award is produced.
        var without = observation("no-partner", event("another-independent-AR-family"), group, policy,
                Phenotype.CONSISTENT_HIGH_HETEROGENEITY, FamilyHistory.COMPATIBLE, null);
        var mixed = calculator.evaluate(group, policy, List.of(qualified, without));
        assertEquals("NOT_EVALUATED", mixed.status(), mixed.toString()); assertEquals("NONE", mixed.code());
        assertEquals("NONE", mixed.strength());
        assertEquals("DENOVO_AR_MIXED_REDUCTION_RULE_NOT_IMPLEMENTED", mixed.reasonCode());
        assertEquals(4, mixed.rawQuarterPoints()); assertEquals(4, mixed.effectiveQuarterPoints());
        assertEquals(2, mixed.events().stream().filter(e -> "COUNTED".equals(e.disposition())).count());
        assertEquals(4, mixed.events().stream().mapToInt(mappedItem -> mappedItem.rawQuarterPoints()).sum());
        // No unqualified/absent event is silently dropped to make the aggregate look uniform.
        assertEquals("MIXED_AR_RULE_NOT_IMPLEMENTED", mixed.strengthAdjustment());
    }

