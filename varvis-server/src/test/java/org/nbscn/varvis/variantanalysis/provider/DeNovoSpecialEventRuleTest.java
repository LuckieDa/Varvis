    private ObjectNode maternal(String id) {
        var n = event(id).put("kind", "MATERNAL_ORIGIN").put("personId", "SYNTHETIC-mother")
                .put("affectedStatus", "UNAFFECTED").put("probandSex", "MALE");
        ((ObjectNode) n.path("trio")).put("personId", "SYNTHETIC-mother")
                .put("motherId", "SYNTHETIC-grandmother").put("fatherId", "SYNTHETIC-grandfather");
        return n;
    }

    @Test void maternalEventUsesTheMothersGrandparentTrioAndNeverTheChildsParents() {
        var group = group("X_LINKED"); var policy = svi(); var n = maternal("maternal-origin");
        var read = read(n, group, policy, unitRegion("NON_PAR"));
        assertTrue(read.issues().isEmpty(), read.toString()); var special = read.value(); assertNotNull(special);
        var inheritedChild = new Facts(group, TargetTest.PRESENT, TargetTest.PRESENT, TargetTest.ABSENT_QUALIFIED,
                Parentage.INCONCLUSIVE, Parentage.INCONCLUSIVE, Phenotype.CONSISTENT, FamilyHistory.COMPATIBLE, special);
        var motherFacts = special.eventFacts(inheritedChild);
        assertEquals(TargetTest.ABSENT_QUALIFIED, motherFacts.mother());
        assertEquals(TargetTest.ABSENT_QUALIFIED, motherFacts.father()); assertTrue(motherFacts.confirmed());
        assertEquals("SYNTHETIC-grandmother", special.snapshot().at("/trio/motherId").asText());
        var observation = new Observation("SYNTHETIC-mother-original", special.eventId(), SourceKind.LITERATURE_CASE,
                inheritedChild, Independence.ESTABLISHED, special.sourceRefs(), List.of());
        var result = calculator.evaluate(group, policy, List.of(observation));
        assertEquals("MET", result.status(), result.toString()); assertEquals("PS2", result.code());
        assertEquals(4, result.effectiveQuarterPoints()); assertEquals(1, result.events().size());
        assertEquals("FEMALE", special.snapshot().path("sex").asText());
        assertEquals("MALE", special.snapshot().path("probandSex").asText());
        var childTrioInstead = maternal("wrong-trio"); ((ObjectNode) childTrioInstead.path("trio")).put("personId", "SYNTHETIC-child");
        var wrong = evaluate(childTrioInstead, group, policy, Phenotype.CONSISTENT, FamilyHistory.COMPATIBLE, unitRegion("NON_PAR"));
        assertEquals("NOT_EVALUATED", wrong.status()); reason(wrong, "DENOVO_EVENT_PERSON_TRIO_CONFLICT");
    }

