CREATE TABLE IF NOT EXISTS variant_analysis_job (
    id CHAR(36) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    stored_file_name VARCHAR(255) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    genome_assembly VARCHAR(16) NOT NULL,
    analysis_mode VARCHAR(16) NOT NULL,
    requested_sample_id VARCHAR(255) NULL,
    selected_sample_id VARCHAR(255) NULL,
    status VARCHAR(32) NOT NULL,
    normalization_applied BOOLEAN NOT NULL DEFAULT FALSE,
    normalization_engine VARCHAR(64) NULL,
    warnings_json TEXT NULL,
    error_message TEXT NULL,
    sample_count INT NULL,
    input_site_count INT NULL,
    variant_count INT NULL,
    multi_allelic_site_count INT NULL,
    snv_count INT NULL,
    indel_count INT NULL,
    mnv_count INT NULL,
    other_count INT NULL,
    pass_count INT NULL,
    filtered_count INT NULL,
    missing_depth_count INT NULL,
    missing_genotype_quality_count INT NULL,
    phenotype_summary_schema_version VARCHAR(16) NULL,
    phenotype_summary_json LONGTEXT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    INDEX idx_variant_analysis_job_status (status),
    INDEX idx_variant_analysis_job_updated_at (updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS variant_analysis_observation (
    analysis_id CHAR(36) NOT NULL,
    variant_order INT NOT NULL,
    genome_assembly VARCHAR(16) NOT NULL,
    chromosome VARCHAR(64) NOT NULL,
    variant_position INT NOT NULL,
    reference_allele TEXT NOT NULL,
    alternate_allele TEXT NOT NULL,
    sample_id VARCHAR(255) NULL,
    genotype VARCHAR(64) NULL,
    depth INT NULL,
    genotype_quality INT NULL,
    allele_depths VARCHAR(255) NULL,
    allele_balance DOUBLE NULL,
    filter_status VARCHAR(255) NULL,
    variant_type VARCHAR(32) NOT NULL,
    original_record TEXT NULL,
    PRIMARY KEY (analysis_id, variant_order),
    CONSTRAINT fk_variant_analysis_observation_job
        FOREIGN KEY (analysis_id) REFERENCES variant_analysis_job (id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS variant_analysis_event (
    id BIGINT NOT NULL AUTO_INCREMENT,
    analysis_id CHAR(36) NOT NULL,
    status VARCHAR(32) NOT NULL,
    message VARCHAR(1000) NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    INDEX idx_variant_analysis_event_job (analysis_id, created_at),
    CONSTRAINT fk_variant_analysis_event_job
        FOREIGN KEY (analysis_id) REFERENCES variant_analysis_job (id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS variant_analysis_interpretation (
    analysis_id CHAR(36) NOT NULL,
    variant_order INT NOT NULL,
    candidate_id VARCHAR(128) NOT NULL,
    canonical_variant_id VARCHAR(1024) NOT NULL,
    variant_id VARCHAR(1024) NOT NULL,
    priority_tier VARCHAR(32) NOT NULL,
    ranking_score DOUBLE NOT NULL,
    genome_assembly VARCHAR(16) NULL,
    chromosome VARCHAR(64) NULL,
    variant_position INT NULL,
    reference_allele TEXT NULL,
    alternate_allele TEXT NULL,
    sample_id VARCHAR(255) NULL,
    genotype VARCHAR(64) NULL,
    filter_status VARCHAR(255) NULL,
    variant_type VARCHAR(32) NULL,
    consequences_json TEXT NULL,
    cadd_score DOUBLE NULL,
    alpha_missense_score DOUBLE NULL,
    alpha_genome_score DOUBLE NULL,
    carried_alt BOOLEAN NOT NULL DEFAULT TRUE,
    analysis_bucket VARCHAR(64) NULL,
    summary_only BOOLEAN NOT NULL DEFAULT FALSE,
    large_file_mode BOOLEAN NOT NULL DEFAULT FALSE,
    expensive_annotation_skipped BOOLEAN NOT NULL DEFAULT FALSE,
    expensive_annotation_skipped_reason TEXT NULL,
    cheap_gate_reason_text TEXT NULL,
    full_interpretation_available BOOLEAN NOT NULL DEFAULT TRUE,
    payload_json LONGTEXT NOT NULL,
    PRIMARY KEY (analysis_id, variant_order),
    UNIQUE INDEX uq_variant_analysis_interpretation_candidate_id (analysis_id, candidate_id),
    INDEX idx_variant_analysis_interpretation_rank (analysis_id, ranking_score),
    INDEX idx_variant_analysis_interpretation_candidate (analysis_id, carried_alt, ranking_score),
    INDEX idx_variant_analysis_interpretation_tier (analysis_id, priority_tier),
    INDEX idx_variant_analysis_interpretation_bucket (analysis_id, analysis_bucket),
    CONSTRAINT fk_variant_analysis_interpretation_job
        FOREIGN KEY (analysis_id) REFERENCES variant_analysis_job (id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS variant_analysis_enhancement (
    id CHAR(36) NOT NULL,
    analysis_id CHAR(36) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    requested_candidate_limit INT NOT NULL,
    selected_candidate_count INT NOT NULL DEFAULT 0,
    completed_count INT NOT NULL DEFAULT 0,
    unavailable_count INT NOT NULL DEFAULT 0,
    error_message TEXT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    INDEX idx_variant_analysis_enhancement_job (analysis_id, created_at),
    CONSTRAINT fk_variant_analysis_enhancement_job
        FOREIGN KEY (analysis_id) REFERENCES variant_analysis_job (id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

