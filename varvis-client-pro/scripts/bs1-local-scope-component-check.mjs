import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
const project = path.resolve(import.meta.dirname, '..');
const [resultFile, destination] = process.argv.slice(2);
if (!resultFile || !destination) throw new Error('Supply an actual saved local BS1 run and isolated output directory');
const run = JSON.parse(fs.readFileSync(resultFile, 'utf8')), output = path.resolve(destination);
fs.mkdirSync(output, { recursive: true });
const component = path.join(project, 'src/pages/varvis/ChromosomeVisualization/components/OrdinaryAcmgEvaluationPanel.jsx');
const utils = path.join(project, 'src/pages/varvis/ChromosomeVisualization/utils/acmgInput.js');
const expose = { name: 'expose-saved-component', setup(b) {
    b.onLoad({ filter: /OrdinaryAcmgEvaluationPanel\.jsx$/ }, () => ({ contents: fs.readFileSync(component, 'utf8') + '\nexport {SavedResult};', loader: 'jsx', resolveDir: path.dirname(component) }));
} };
await build({ stdin: { contents: `import React from 'react';import {renderToStaticMarkup} from 'react-dom/server';import {SavedResult} from ${JSON.stringify(component)};
export {evidenceCards,reasonHelp,validateSavedRun} from ${JSON.stringify(utils)};
export const saved=r=>renderToStaticMarkup(<SavedResult run={r} criteria={r.enabledCriteria}/>);`, resolveDir: project, loader: 'jsx' }, bundle: true, platform: 'node', format: 'cjs', outfile: path.join(output, 'checks.cjs'), plugins: [expose], define: { 'process.env.NODE_ENV': '"production"' }, logLevel: 'warning' });
const api = createRequire(import.meta.url)(path.join(output, 'checks.cjs'));
const original = JSON.stringify(run);
const entries = run.candidates.map((c) => api.evidenceCards(c, ['ACMG_AMP_2015:BS1'])[0].entries[0]);
assert.ok(entries.some((e) => e.evaluation.evaluationResult.status === 'MET'));
assert.ok(entries.some((e) => e.evaluation.evaluationResult.status === 'NOT_MET'));
assert.ok(entries.some((e) => e.evaluation.evaluationResult.status === 'NOT_EVALUATED'));
const positive = run.candidates.find((c) => c.attempts[0].bs1.evaluation.evaluationResult.status === 'MET');
assert.ok(positive);
const positiveEntry = api.evidenceCards(positive, ['ACMG_AMP_2015:BS1'])[0].entries[0];
const details = Object.fromEntries(positiveEntry.details);
assert.match(details['数据范围'], /exomes 4.1/); assert.equal(details['exomes 原生 FILTER'], 'PASS');
assert.ok(details['同祖源普通 AF（辅助）']); assert.match(details['阈值与比较'], /0.000033/);
assert.equal(details['joint FILTER'], undefined);
for (const kind of ['CONTEXT', 'ALLELE', 'SCOPE', 'DATASET', 'METRIC']) {
    const broken = structuredClone(positive), value = broken.attempts[0].bs1;
    if (kind === 'CONTEXT') value.evaluation.contextId = 'other-context';
    if (kind === 'ALLELE') value.observation.queryAllele.position++;
    if (kind === 'SCOPE') delete value.dataScope;
    if (kind === 'DATASET') value.dataScope.dataset = 'JOINT';
    if (kind === 'METRIC') value.evidence.measurements.push({ metricId: 'gnomad.joint.faf95max', rawValue: '0.1' });
    assert.equal(api.evidenceCards(broken, ['ACMG_AMP_2015:BS1'])[0].entries[0].evaluation.evaluationResult.reasonCode, 'BS1_SAVED_RESULT_ASSOCIATION_INVALID');
}
assert.match(api.reasonHelp('BS1_NO_RECORD'), /不能.*零/);
assert.match(api.reasonHelp('BS1_LOCAL_AN_INSUFFICIENT'), /2000/);
const html = api.saved(run); assert.match(html, /已保存的证据结果/); assert.match(html, /BS1/);
assert.match(html, /BS1 按确认的疾病与遗传方式匹配阈值/);
assert.doesNotMatch(html, /PM2／BS1 暂不执行/);
const historical = structuredClone(run); delete historical.executionProfile.bs1RuntimeBinding;
assert.match(api.saved(historical), /PM2／BS1 暂不执行/);
assert.equal(original, JSON.stringify(run));
fs.writeFileSync(path.join(output, 'saved.html'), html);
fs.writeFileSync(path.join(output, 'expected-download.json'), JSON.stringify(run, null, 2));
await build({ stdin: { contents: `import React from 'react';import {createRoot} from 'react-dom/client';import {SavedResult} from ${JSON.stringify(component)};
const run=${original};createRoot(document.getElementById('root')).render(<SavedResult run={run} criteria={run.enabledCriteria}/>);`, resolveDir: project, loader: 'jsx' }, bundle: true, platform: 'browser', format: 'iife', outfile: path.join(output, 'page.js'), plugins: [expose], define: { 'process.env.NODE_ENV': '"production"' }, logLevel: 'warning' });
fs.writeFileSync(path.join(output, 'index.html'), '<!doctype html><meta charset="utf-8"><title>BS1 本地保存结果核验</title><body style="padding:24px;background:#fafafa"><p>BS1 本地接入：真实保存结果的只读回放。无业务提交或科学执行。</p><div id="root"></div><script src="page.js"></script>');
fs.writeFileSync(path.join(output, 'component-checks.json'), JSON.stringify({ passed: 22, actualSavedResult: true, completeInputUnchanged: true, downloadFileObtained: false, expectedFilename: `acmg-${run.runId}.json` }, null, 2));
console.log('22 BS1 component assertions passed; complete saved JSON preserved; actual download pending user');
